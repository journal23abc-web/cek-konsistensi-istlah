// core/report.js
// Builds a downloadable Markdown report from rendered finding cards.
// Kept framework-free: takes plain data, returns a string.

export function buildMarkdownReport(categoryBlocks) {
  const lines = ['# Terminology Consistency Report', ''];
  const total = categoryBlocks.reduce((s, c) => s + c.items.reduce((s2, it) => s2 + it.occurrenceCount, 0), 0);
  const groups = categoryBlocks.reduce((s, c) => s + c.items.length, 0);
  lines.push('Total occurrences: ' + total);
  lines.push('Total groups: ' + groups);
  lines.push('');
  for (const block of categoryBlocks) {
    if (!block.items.length) continue;
    lines.push('## ' + block.title);
    for (const item of block.items) {
      lines.push('- ' + item.variantSummary);
      for (const ctx of item.contexts) lines.push('  - context: ' + ctx);
    }
    lines.push('');
  }
  return lines.join('\n');
}

export function downloadMarkdown(filename, content) {
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

// Severity bucket for the printable report's three-color system
// (.rp-issue.error / .warning / .suggestion — red / amber / cyan).
const SEVERITY = {
  case: 'error', fuzzy: 'error', identifier: 'error', phrase: 'error',
  hyphenation: 'warning', spelling: 'warning', acronym: 'warning', reorder: 'warning',
  glossary: 'suggestion', semantic: 'suggestion'
};

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// Builds the inner HTML of a .report-page element (see shared.css) from the
// same category-block data used for the Markdown export.
export function buildPrintableReportHTML(categoryBlocks, meta) {
  const total = categoryBlocks.reduce((s, c) => s + c.items.length, 0);
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });

  let html = '';
  html += '<h1>Terminology Consistency Report</h1>';
  html += '<div class="rp-meta">Generated ' + esc(dateStr) + '</div>';
  html += '<div class="rp-meta">Manuscript length: ' + esc(meta.wordCount) + ' words</div>';
  html += '<table style="margin-top:10px;"><tbody>';
  html += '<tr><td class="k">Total groups flagged</td><td class="v">' + total + '</td></tr>';
  for (const block of categoryBlocks) {
    html += '<tr><td class="k">' + esc(block.title) + '</td><td class="v">' + block.items.length + '</td></tr>';
  }
  html += '</tbody></table>';

  if (total === 0) {
    html += '<p class="rp-empty">No inconsistencies found in the selected categories.</p>';
  }

  for (const block of categoryBlocks) {
    if (!block.items.length) continue;
    html += '<h2>' + esc(block.title) + '</h2>';
    for (const item of block.items) {
      const sevClass = SEVERITY[block.key] || 'suggestion';
      html += '<div class="rp-issue ' + sevClass + '">';
      html += '<div class="t">' + esc(item.variantSummary) + '<span class="loc">' + item.occurrenceCount + ' occurrence(s)</span></div>';
      if (item.contexts.length) {
        html += '<div class="d">' + item.contexts.slice(0, 2).map(esc).join('<br>') + '</div>';
      }
      html += '</div>';
    }
  }

  html += '<div class="rp-foot">Generated by a local, heuristic text-pattern checker. Every finding above is a candidate for a human editor to verify \u2014 not a confirmed error, and not a substitute for your target journal\u2019s style guide.</div>';
  return html;
}
